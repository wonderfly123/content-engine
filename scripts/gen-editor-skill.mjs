// Bundles the editor skill's markdown files (workers/editor/skill, the repo defaults) into the app as
// lib/editor/skill-defaults.generated.ts, so the Admin skill editor and the job sender have them on
// Vercel without reading the worker folder at run time.
// Usage: npm run skill:gen   (after changing any .md under workers/editor/skill; a test fails until you do)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SKILL = path.join(ROOT, "workers/editor/skill");
const OUT = path.join(ROOT, "lib/editor/skill-defaults.generated.ts");

/** Every .md file under the skill folder except scripts/, as forward-slash paths, sorted. */
export function skillMarkdownPaths(dir = SKILL, rel = "") {
  const out = [];
  for (const entry of readdirSync(path.join(dir, rel), { withFileTypes: true })) {
    const p = rel ? `${rel}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      if (p !== "scripts") out.push(...skillMarkdownPaths(dir, p));
    } else if (entry.name.endsWith(".md")) out.push(p);
  }
  return out.sort();
}

export function render() {
  const lines = [
    "// GENERATED by scripts/gen-editor-skill.mjs from workers/editor/skill. Do not edit; run `npm run skill:gen`.",
    "export const SKILL_DEFAULTS: Readonly<Record<string, string>> = {",
  ];
  for (const p of skillMarkdownPaths()) lines.push(`  ${JSON.stringify(p)}: ${JSON.stringify(readFileSync(path.join(SKILL, p), "utf8"))},`);
  lines.push("};", "");
  return lines.join("\n");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(OUT, render());
  console.log(`wrote ${path.relative(ROOT, OUT)} (${skillMarkdownPaths().length} files)`);
}
